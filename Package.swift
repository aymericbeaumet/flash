// swift-tools-version: 5.10
import PackageDescription

// Project-wide swift compiler flags.
//
// - `-warnings-as-errors` forces fresh code to compile cleanly; we don't
//   want to ship master with a backlog of "soft" warnings that mask real
//   regressions when something genuinely starts misbehaving.
// - The upcoming-feature flags walk the codebase a few Swift-evolution
//   defaults early so the Swift-6 transition is a no-op: existential-any
//   syntax stays explicit, integer-literal narrowing is rejected at
//   compile time, and importing a module no longer re-exports its own
//   imports by accident.
let strictSwiftSettings: [SwiftSetting] = [
  .unsafeFlags(["-warnings-as-errors"]),
  .enableUpcomingFeature("ForwardTrailingClosures"),
  .enableUpcomingFeature("ConciseMagicFile"),
  .enableUpcomingFeature("BareSlashRegexLiterals"),
  .enableUpcomingFeature("DeprecateApplicationMain"),
  .enableUpcomingFeature("ImportObjcForwardDeclarations"),
  .enableUpcomingFeature("DisableOutwardActorInference"),
]

// The resident's own modules are optimized in the debug configuration too:
// `install:dev` and `swift test` both build it, and the dev resident is the
// one in daily use. Unoptimized, the 1 Hz status bar's evaluation and layout
// cost 3–4× as much CPU (`StatusBarCostBenchmarkTests`), and so does every
// other hot path. `-assert-config Debug` keeps `assert` live for tests, and
// sharing the debug build directory keeps `swift test` and the dev install
// from rebuilding each other's products.
let optimizedInDebug: [SwiftSetting] = [
  .unsafeFlags(["-O", "-assert-config", "Debug"], .when(configuration: .debug))
]

