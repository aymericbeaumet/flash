import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";
import { schemaFile, stateTypes, typesFile, type Schema } from "./scripts/state-types.ts";

test("a schema becomes the types a value of it has", () => {
  const schema: Schema = {
    $schema: "http://json-schema.org/draft-07/schema#",
    description: "The snapshot.",
    type: "object",
    additionalProperties: false,
    required: ["at", "plugins", "overlay", "bar"],
    properties: {
      at: { type: "integer", minimum: 0, description: "When it was built." },
      plugins: { type: "array", items: { $ref: "#/definitions/plugin" } },
      overlay: { anyOf: [{ type: "string", enum: ["hints", "normal"] }, { type: "null" }] },
      bar: { anyOf: [{ $ref: "#/definitions/status_bar" }, { $ref: "#/definitions/empty" }] },
      config: { type: ["object", "string"] },
      "odd-name": { type: "boolean" },
    },
    definitions: {
      empty: { type: "object", maxProperties: 0, description: "No keys */ at all." },
      plugin: {
        type: "object",
        additionalProperties: false,
        required: ["id", "pid", "segments", "run"],
        properties: {
          id: { type: "string" },
          pid: { type: ["integer", "null"] },
          kind: { const: "plugin" },
          segments: { type: "object", additionalProperties: { type: "string", maxLength: 9 } },
          run: {
            anyOf: [
              { type: "array", items: { type: "array", items: { type: "string" } }, minItems: 1 },
              { type: "null" },
            ],
          },
          frames: { type: "array", items: { type: ["number", "null"] } },
          limits: {
            type: "object",
            additionalProperties: false,
            required: ["max"],
            properties: { max: { type: "number" } },
          },
        },
      },
      status_bar: { type: "object", properties: { height: { type: "number" } } },
      source_node: {
        type: "object",
        properties: { $: { $ref: "#/definitions/plugin" } },
        additionalProperties: { $ref: "#/definitions/source_node" },
      },
      monitor: {
        oneOf: [{ $ref: "#/definitions/plugin" }, { $ref: "#/definitions/status_bar" }],
      },
    },
  };
  assert.equal(
    stateTypes(schema),
    `// Generated by scripts/state-types.ts from docs/schema/inspector/state.schema.json.
// Do not edit: change the schema, then run \`mise run build:schema\`.

/** The snapshot. */
export interface StateSnapshot {
  /** When it was built. */
  at: number;
  plugins: PluginInfo[];
  overlay: "hints" | "normal" | null;
  bar: StatusBar | Empty;
  config?: Record<string, unknown> | string;
  "odd-name"?: boolean;
}

/** No keys *\\/ at all. */
export type Empty = Record<string, never>;

export interface PluginInfo {
  id: string;
  pid: number | null;
  kind?: "plugin";
  segments: Record<string, string>;
  run: string[][] | null;
  frames?: (number | null)[];
  limits?: {
    max: number;
  };
}

export interface StatusBar {
  height?: number;
  [key: string]: unknown;
}

export interface SourceNode {
  $?: PluginInfo;
  [key: string]: SourceNode | PluginInfo | undefined;
}

export type Monitor = PluginInfo | StatusBar;
`,
  );
});

test("a schema the generator cannot read faithfully is refused, never guessed", () => {
  const refused = (schema: Schema, message: RegExp) =>
    assert.throws(() => stateTypes({ type: "object", properties: { key: schema } }), message);
  refused({ type: "string", format: "date-time" }, /#\/key: format is not a keyword/);
  refused({ $ref: "other.schema.json#/definitions/x" }, /is not a local definition/);
  refused({ description: "anything" }, /#\/key: no type/);
  refused({ type: "tuple" }, /type tuple is not one/);
  refused({ type: "object", required: ["gone"], properties: { here: { type: "string" } } }, /gone/);
  assert.throws(
    () =>
      stateTypes({ type: "object", definitions: { a_b: { type: "null" }, aB: { type: "null" } } }),
    /aB and a_b are both AB/,
  );
});

/**
 * `mise run build:schema` writes the snapshot's types from its schema; the
 * committed copy is what the page compiles against.
 */
test("the committed snapshot types are what the schema generates", () => {
  const generated = stateTypes(JSON.parse(readFileSync(schemaFile, "utf8")) as Schema);
  assert.ok(
    readFileSync(typesFile, "utf8") === generated,
    "Inspector/src/lib/state.generated.ts is stale: run mise run build:schema",
  );
  for (const name of ["StateSnapshot", "PluginInfo", "MappingsState", "KeyboardState", "Monitor"])
    assert.match(generated, new RegExp(`^export (interface|type) ${name}\\b`, "m"), name);
});
