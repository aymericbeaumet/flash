#!/usr/bin/env bash
set -euo pipefail

# Refresh the searchproviders plugin's vendored bang snapshot: Kagi's community
# list (https://github.com/kagisearch/bangs, MIT License), converted from
# data/bangs.json at one pinned commit into Plugins/searchproviders/kagi-bangs.tsv,
# with the repository's LICENSE copied into the plugin's notices. The plugin
# embeds the TSV at compile time; nothing runs this at build time.
#
# DuckDuckGo's own list (https://duckduckgo.com/bang.js) carries no licence
# that permits redistribution, so it is never vendored: the plugin downloads
# it at run time into its data directory (see docs/flashlight.md).
#
# Usage: update-bangs.sh [<commit>]
#   <commit>  a full kagisearch/bangs commit SHA; default: main, resolved to
#             its SHA so the snapshot names exactly what it was built from.
#
# Requires: curl, python3.

PROJECT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
PLUGIN_DIR="$PROJECT_DIR/Plugins/searchproviders"
REPO="kagisearch/bangs"

commit="${1:-}"
if [[ -z "$commit" ]]; then
  commit="$(curl -fsSL "https://api.github.com/repos/$REPO/commits/main" |
    python3 -I -c 'import json, sys; print(json.load(sys.stdin)["sha"])')"
fi
if [[ ! "$commit" =~ ^[0-9a-f]{40}$ ]]; then
  echo "error: expected a full 40-character commit SHA, got: $commit" >&2
  exit 2
fi

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
curl -fsSL "https://raw.githubusercontent.com/$REPO/$commit/data/bangs.json" -o "$work/bangs.json"
curl -fsSL "https://raw.githubusercontent.com/$REPO/$commit/LICENSE" -o "$work/LICENSE"

python3 -I - "$work/bangs.json" "$commit" "$PLUGIN_DIR/kagi-bangs.tsv" <<'PY'
import json
import sys

source, commit, destination = sys.argv[1:4]
FLAGS = {
    "open_base_path": "b",
    "open_snap_domain": "d",
    "url_encode_placeholder": "e",
    "url_encode_space_to_plus": "p",
}


def field(entry, key, required=False):
    value = entry.get(key)
    if value is None:
        if required:
            raise SystemExit(f"bang without {key}: {entry!r}")
        return ""
    if not isinstance(value, str):
        raise SystemExit(f"bang {entry.get('t')!r}: {key} is not a string")
    if any(character in value for character in "\t\r\n"):
        raise SystemExit(f"bang {entry.get('t')!r}: {key} holds a tab or newline")
    return value


def flags(entry):
    # Kagi enables every flag when `fmt` is absent; an explicit list is
    # exhaustive, and an empty one is written as "-".
    if "fmt" not in entry:
        return "bdep"
    letters = set()
    for flag in entry["fmt"]:
        if flag not in FLAGS:
            raise SystemExit(f"bang {entry.get('t')!r}: unknown fmt flag {flag!r}")
        letters.add(FLAGS[flag])
    return "".join(sorted(letters)) or "-"


rows = []
for entry in json.load(open(source, encoding="utf-8")):
    aliases = entry.get("ts", [])
    if not isinstance(aliases, list) or not all(isinstance(alias, str) for alias in aliases):
        raise SystemExit(f"bang {entry.get('t')!r}: ts is not a list of strings")
    if any(" " in alias or "\t" in alias for alias in aliases):
        raise SystemExit(f"bang {entry.get('t')!r}: an alias holds whitespace")
    rows.append([
        field(entry, "t", required=True),
        " ".join(aliases),
        flags(entry),
        field(entry, "u", required=True).strip(),
        field(entry, "s"),
        field(entry, "d"),
        field(entry, "ad"),
        field(entry, "c"),
        field(entry, "sc"),
        field(entry, "x"),
    ])
# Sorted by the trigger lowercased one character at a time, the fold the
# plugin's binary search uses.
rows.sort(key=lambda row: "".join(character.lower() for character in row[0]))

with open(destination, "w", encoding="utf-8", newline="\n") as output:
    output.write(
        "# Kagi community bangs (https://github.com/kagisearch/bangs), data/bangs.json\n"
        f"# at commit {commit}. MIT License: notices/kagisearch-bangs-LICENSE.\n"
        "# Generated by Scripts/update-bangs.sh; do not edit by hand.\n"
        "# Columns (tab-separated): trigger, aliases (space-separated), format flags,\n"
        "# URL template ({{{s}}} is the query), site name, domain, snap domain,\n"
        "# category, subcategory, query pattern. Format flags: b open_base_path,\n"
        "# d open_snap_domain, e url_encode_placeholder, p url_encode_space_to_plus;\n"
        "# - for none.\n"
    )
    for row in rows:
        output.write("\t".join(row) + "\n")
print(f"Wrote {len(rows)} bangs to {destination}")
PY

mkdir -p "$PLUGIN_DIR/notices"
cp "$work/LICENSE" "$PLUGIN_DIR/notices/kagisearch-bangs-LICENSE"
echo "Pinned kagisearch/bangs at $commit"
