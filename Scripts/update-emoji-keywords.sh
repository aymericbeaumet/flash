#!/usr/bin/env bash
set -euo pipefail

# Refresh the emojis plugin's vendored CLDR keyword table: the English emoji
# annotations of Unicode CLDR (https://github.com/unicode-org/cldr, Unicode
# License v3), common/annotations/en.xml and common/annotationsDerived/en.xml
# at one pinned commit, reduced to the keywords of the glyphs listed in
# Plugins/emojis/emoji.txt and written to Plugins/emojis/cldr-keywords.tsv,
# with the repository's LICENSE copied into the plugin's notices. The plugin
# embeds the TSV at compile time; nothing runs this at build time and nothing
# is fetched at run time.
#
# Only the keywords are vendored. The short names (`tts` annotations) add
# nothing the keywords and the Unicode names do not already say, and the
# other locales are not searched.
#
# Usage: update-emoji-keywords.sh [<ref>]
#   <ref>  a unicode-org/cldr release tag (release-NN) or full commit SHA;
#          default: release-49. The ref is resolved to its SHA so the table
#          names exactly what it was built from.
#
# Requires: curl, python3.

PROJECT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
PLUGIN_DIR="$PROJECT_DIR/Plugins/emojis"
REPO="unicode-org/cldr"

ref="${1:-release-49}"
commit="$(curl -fsSL "https://api.github.com/repos/$REPO/commits/$ref" |
  python3 -I -c 'import json, sys; print(json.load(sys.stdin)["sha"])')"
if [[ ! "$commit" =~ ^[0-9a-f]{40}$ ]]; then
  echo "error: could not resolve $ref to a full 40-character commit SHA, got: $commit" >&2
  exit 2
fi

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
curl -fsSL "https://raw.githubusercontent.com/$REPO/$commit/common/annotations/en.xml" -o "$work/annotations.xml"
curl -fsSL "https://raw.githubusercontent.com/$REPO/$commit/common/annotationsDerived/en.xml" -o "$work/derived.xml"
curl -fsSL "https://raw.githubusercontent.com/$REPO/$commit/LICENSE" -o "$work/LICENSE"

python3 -I - "$work/annotations.xml" "$work/derived.xml" "$PLUGIN_DIR/emoji.txt" \
  "$ref" "$commit" "$PLUGIN_DIR/cldr-keywords.tsv" <<'PY'
import sys
import xml.etree.ElementTree as ET

annotations, derived, emoji, ref, commit, destination = sys.argv[1:7]
# CLDR writes every code point sequence without the emoji presentation
# selector; so does emoji.txt, but the lookup strips it from both sides.
VARIATION_SELECTOR_16 = "️"


def keyword_table(path):
    table = {}
    for element in ET.parse(path).getroot().iter("annotation"):
        if element.get("type") == "tts":
            continue
        glyph = element.get("cp", "").replace(VARIATION_SELECTOR_16, "")
        keywords = [keyword.strip() for keyword in (element.text or "").split("|")]
        keywords = [keyword for keyword in keywords if keyword]
        if not glyph or not keywords:
            raise SystemExit(f"{path}: annotation without a glyph or keywords: {element.attrib!r}")
        if any(character in keyword for keyword in keywords for character in "\t\r\n|"):
            raise SystemExit(f"{path}: {glyph}: a keyword holds a tab, newline or bar")
        if len(set(keywords)) != len(keywords):
            raise SystemExit(f"{path}: {glyph}: repeated keyword")
        if glyph in table:
            raise SystemExit(f"{path}: {glyph}: annotated twice")
        table[glyph] = keywords
    return table


table = keyword_table(annotations)
for glyph, keywords in keyword_table(derived).items():
    if glyph in table:
        raise SystemExit(f"{glyph}: annotated in both files")
    table[glyph] = keywords

glyphs = []
for line in open(emoji, encoding="utf-8"):
    if "\t" not in line:
        continue
    glyph = line.split("\t", 1)[0].strip()
    if glyph:
        glyphs.append(glyph)

rows = []
for glyph in glyphs:
    keywords = table.get(glyph.replace(VARIATION_SELECTOR_16, ""))
    if keywords is not None:
        rows.append((glyph, keywords))

pinned = f"commit {commit}" if ref == commit else f"{ref}, commit {commit}"
with open(destination, "w", encoding="utf-8", newline="\n") as output:
    output.write(
        "# Unicode CLDR emoji keywords (https://github.com/unicode-org/cldr),\n"
        "# common/annotations/en.xml and common/annotationsDerived/en.xml at\n"
        f"# {pinned}.\n"
        "# Unicode License v3: notices/cldr-annotations-LICENSE.\n"
        "# Generated by Scripts/update-emoji-keywords.sh; do not edit by hand.\n"
        "# Columns (tab-separated): glyph as written in emoji.txt, keywords\n"
        "# (|-separated, in CLDR order). Only the glyphs of emoji.txt are listed,\n"
        "# in its order; rerun the script after extending it.\n"
    )
    for glyph, keywords in rows:
        output.write(f"{glyph}\t{'|'.join(keywords)}\n")
print(f"Wrote keywords for {len(rows)} of {len(glyphs)} glyphs to {destination}")
PY

mkdir -p "$PLUGIN_DIR/notices"
cp "$work/LICENSE" "$PLUGIN_DIR/notices/cldr-annotations-LICENSE"
echo "Pinned $REPO at $commit"
