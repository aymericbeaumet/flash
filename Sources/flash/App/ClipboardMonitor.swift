import AppKit

/// Watches the general pasteboard for changes and reports a new copy.
///
/// macOS exposes no pasteboard-change notification, so the only mechanism is
/// to compare `NSPasteboard.changeCount` (a monotonic integer the system bumps
/// on every write) against the last seen value. That makes this one of the few
/// places a poll is the only option — so it runs on the shared
/// `PollScheduler` rather than its own timer.
///
/// This lives in core beside the clipboard history store.
final class ClipboardMonitor {
  private let pasteboard: NSPasteboard
  private let onChange: (ClipboardCapture.Item) -> Void
  /// The 2 Hz poll runs on a utility queue. `NSPasteboard` reads are
  /// thread-safe, and image or HTML conversion must stay off the main run
  /// loop that hosts the keyboard tap.
  private let queue = DispatchQueue(label: "flash.clipboard", qos: .utility)
  private let scheduler: PollScheduler
  private var registered = false
  private var lastChangeCount: Int

  /// nspasteboard.org markers for payloads a clipboard history must not
  /// record: `ConcealedType` (passwords and other secrets), `TransientType`
  /// (content its writer restores shortly) and `AutoGeneratedType` (content
  /// an app wrote without a user copy). Marked payloads never reach history.
  static let unrecordedTypes: Set<NSPasteboard.PasteboardType> = [
    NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
    NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
    NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
  ]

  static let clientID = "core:clipboard"

  init(
    pasteboard: NSPasteboard = .general,
    scheduler: PollScheduler = .shared,
    onChange: @escaping (ClipboardCapture.Item) -> Void
  ) {
    self.pasteboard = pasteboard
    self.scheduler = scheduler
    self.onChange = onChange
    self.lastChangeCount = pasteboard.changeCount
  }

  /// `.normal`: nothing on screen waits on this watcher, so it never needs
  /// `.high` precision, but a copy that lands late reaches the clipboard
  /// history late — and someone can copy and open that history within a
  /// second — so it keeps ordinary slack rather than background slack.
  func start(interval: TimeInterval = 0.5) {
    guard !registered else { return }
    registered = true
    scheduler.register(
      Self.clientID, everyMs: Int(interval * 1000), priority: .normal, on: queue
    ) { [weak self] in self?.poll() }
  }

  func stop() {
    guard registered else { return }
    registered = false
    scheduler.unregister(Self.clientID)
  }

  private func poll() {
    let current = pasteboard.changeCount
    guard current != lastChangeCount else { return }
    lastChangeCount = current
    guard Self.isRecordable(pasteboard.types ?? []) else { return }
    guard let item = ClipboardCapture.read(pasteboard) else { return }
    onChange(item)
  }

  /// Whether a payload declaring `types` may enter clipboard history.
  static func isRecordable(_ types: [NSPasteboard.PasteboardType]) -> Bool {
    !types.contains(where: unrecordedTypes.contains)
  }

  deinit { stop() }
}
