import Foundation

/// Shell completions and the `flash(1)` man page, generated from the command
/// table so they list exactly what the CLI resolves: every
/// `<topic> <action>`, its `--options` (with their values when the
/// placeholder enumerates them, `app|screen`), the queries and the
/// command-line words. `flash cli completion --shell=` and `flash cli
/// manpage` print them; the Homebrew cask installs both.
enum CLIReference {
  enum Shell: String, CaseIterable {
    case zsh, bash, fish
  }

  /// One `flash <topic> <action>` (or query) and what it takes.
  struct Entry {
    let topic: String
    let action: String
    let summary: String
    let options: [Option]
  }

  struct Option {
    let name: String
    /// nil for a flag; the values to offer, or empty for free text.
    let values: [String]?
    let syntax: String
  }

  /// Every command and query, sorted by topic then action.
  static var entries: [Entry] {
    var result = URLEventHandler.commandNames.map { name in
      Entry(
        topic: name.topic, action: name.action, summary: URLEventHandler.summary(of: name) ?? "",
        options: (URLEventHandler.commandParameters(of: name) ?? []).map(option))
    }
    for query in FlashQuery.allCases {
      result.append(
        Entry(
          topic: query.name.topic, action: query.name.action, summary: query.summary,
          options: query.options))
    }
    return result.sorted { ($0.topic, $0.action) < ($1.topic, $1.action) }
  }

  /// The words that start a command line without being a topic: `open`,
  /// `flashlight`, `doctor`.
  static var words: [(name: String, description: String)] {
    NormalModeDispatcher.builtinCatalog
  }

  static var topics: [String] {
    Array(Set(entries.map(\.topic))).sorted()
  }

  static func option(_ parameter: CommandParameter) -> Option {
    let flag = "--" + parameter.name.replacingOccurrences(of: "_", with: "-")
    switch parameter.kind {
    case .flag: return Option(name: flag, values: nil, syntax: parameter.syntax)
    case .integer: return Option(name: flag, values: [], syntax: parameter.syntax)
    case .text(let placeholder):
      let choices = placeholder.split(separator: "|").map(String.init)
      let enumerates =
        choices.count > 1
        && choices.allSatisfy { $0.allSatisfy { $0.isLetter || $0.isNumber || $0 == "_" } }
      return Option(name: flag, values: enumerates ? choices : [], syntax: parameter.syntax)
    }
  }

  static func completion(for shell: Shell) -> String {
    switch shell {
    case .zsh: return zsh()
    case .bash: return bash()
    case .fish: return fish()
    }
  }

  private static let header =
    "Generated by `flash cli completion`; regenerate after updating Flash. Plugin commands "
    + "(`flash <command> <subcommand>`) depend on what is installed and are not listed."

  /// A topic's description: its actions.
  private static func describe(topic: String) -> String {
    let actions = entries.filter { $0.topic == topic }.map(\.action)
    let shown = actions.prefix(6).joined(separator: ", ")
    return actions.count > 6 ? "\(shown), …" : shown
  }

  // MARK: zsh

  private static func zshQuote(_ text: String) -> String {
    "'" + text.replacingOccurrences(of: "'", with: "'\\''") + "'"
  }

  private static func zshDescribed(_ name: String, _ description: String) -> String {
    zshQuote(name.replacingOccurrences(of: ":", with: "\\:") + ":" + description)
  }

  private static func zsh() -> String {
    var lines = [
      "#compdef flash", "# \(header)", "", "_flash() {",
      "  local -a topics actions flags valued values",
    ]
    lines.append("  topics=(")
    for topic in topics { lines.append("    \(zshDescribed(topic, describe(topic: topic)))") }
    for word in words { lines.append("    \(zshDescribed(word.name, word.description))") }
    lines.append("  )")
    lines += [
      "  if (( CURRENT == 2 )); then",
      "    _describe -t topics 'flash command' topics",
      "    return",
      "  fi",
      "  if (( CURRENT == 3 )); then",
      "    case $words[2] in",
    ]
    for topic in topics {
      let actions = entries.filter { $0.topic == topic }.map {
        zshDescribed($0.action, $0.summary)
      }
      lines.append("      \(topic)) actions=(\(actions.joined(separator: " "))) ;;")
    }
    lines += [
      "      *) return 1 ;;",
      "    esac",
      "    _describe -t actions 'flash action' actions",
      "    return",
      "  fi",
      "  local cur=$words[CURRENT]",
      "  case \"$words[2] $words[3]\" in",
    ]
    for entry in entries where !entry.options.isEmpty {
      let flags = entry.options.filter { $0.values == nil }.map {
        zshDescribed($0.name, $0.syntax)
      }
      let valued = entry.options.filter { $0.values != nil }.map {
        zshDescribed($0.name + "=", $0.syntax)
      }
      lines.append(
        "    \(zshQuote("\(entry.topic) \(entry.action)"))) flags=(\(flags.joined(separator: " "))) "
          + "valued=(\(valued.joined(separator: " "))) ;;")
    }
    lines += [
      "    *) return 1 ;;",
      "  esac",
      "  if [[ $cur == --*=* ]]; then",
      "    case \"$words[2] $words[3] ${cur%%=*}\" in",
    ]
    for entry in entries {
      for option in entry.options {
        guard let values = option.values, !values.isEmpty else { continue }
        lines.append(
          "      \(zshQuote("\(entry.topic) \(entry.action) \(option.name)"))) "
            + "values=(\(values.map(zshQuote).joined(separator: " "))) ;;")
      }
    }
    lines += [
      "      *) return 1 ;;",
      "    esac",
      "    compadd -P \"${cur%%=*}=\" -- $values",
      "    return",
      "  fi",
      "  _describe -t flags 'flag' flags",
      "  _describe -t options 'option' valued -S ''",
      "}",
      "",
      "if [[ $zsh_eval_context[-1] == loadautofunc ]]; then",
      "  _flash \"$@\"",
      "else",
      "  compdef _flash flash",
      "fi",
      "",
    ]
    return lines.joined(separator: "\n")
  }

  // MARK: bash

  private static func bashWords(_ words: [String]) -> String {
    "\"" + words.joined(separator: " ") + "\""
  }

  private static func bash() -> String {
    var lines = [
      "# bash completion for flash", "# \(header)", "",
      "_flash() {",
      "  # Bash splits words at '=': read the line itself for the token being typed.",
      "  local line=${COMP_LINE:0:COMP_POINT}",
      "  local -a words",
      "  read -ra words <<<\"$line\"",
      "  [[ $line == *' ' ]] && words+=('')",
      "  local count=${#words[@]} token=${words[${#words[@]}-1]}",
      "  COMPREPLY=()",
      "  if (( count == 2 )); then",
      "    COMPREPLY=($(compgen -W \(bashWords(topics + words.map(\.name))) -- \"$token\"))",
      "    return",
      "  fi",
      "  if (( count == 3 )); then",
      "    case ${words[1]} in",
    ]
    for topic in topics {
      let actions = entries.filter { $0.topic == topic }.map(\.action)
      lines.append(
        "      \(topic)) COMPREPLY=($(compgen -W \(bashWords(actions)) -- \"$token\")) ;;")
    }
    lines += [
      "    esac",
      "    return",
      "  fi",
      "  local command=\"${words[1]} ${words[2]}\"",
      "  if [[ $token == --*=* ]]; then",
      "    local values",
      "    case \"$command ${token%%=*}\" in",
    ]
    for entry in entries {
      for option in entry.options {
        guard let values = option.values, !values.isEmpty else { continue }
        lines.append(
          "      \"\(entry.topic) \(entry.action) \(option.name)\") values=\(bashWords(values)) ;;")
      }
    }
    lines += [
      "      *) return ;;",
      "    esac",
      "    COMPREPLY=($(compgen -W \"$values\" -- \"${token#*=}\"))",
      "    return",
      "  fi",
      "  local options",
      "  case $command in",
    ]
    for entry in entries where !entry.options.isEmpty {
      let names = entry.options.map { $0.values == nil ? $0.name : $0.name + "=" }
      lines.append("    \"\(entry.topic) \(entry.action)\") options=\(bashWords(names)) ;;")
    }
    lines += [
      "    *) return ;;",
      "  esac",
      "  COMPREPLY=($(compgen -W \"$options\" -- \"$token\"))",
      "  # compopt needs bash 4; macOS's /bin/bash 3.2 adds the space.",
      "  [[ ${#COMPREPLY[@]} == 1 && ${COMPREPLY[0]} == *= ]] && type compopt &>/dev/null \\",
      "    && compopt -o nospace",
      "}",
      "complete -F _flash flash",
      "",
    ]
    return lines.joined(separator: "\n")
  }

  // MARK: fish

  private static func fishQuote(_ text: String) -> String {
    "'"
      + text.replacingOccurrences(of: "\\", with: "\\\\")
      .replacingOccurrences(of: "'", with: "\\'") + "'"
  }

  private static func fish() -> String {
    var lines = [
      "# fish completion for flash", "# \(header)", "",
      "function __flash_at_command",
      "  set -l words (commandline -opc)",
      "  test (count $words) -ge 3; and test \"$words[2] $words[3]\" = \"$argv\"",
      "end",
      "",
      "complete -c flash -f",
    ]
    for topic in topics {
      lines.append(
        "complete -c flash -n __fish_use_subcommand -a \(fishQuote(topic)) "
          + "-d \(fishQuote(describe(topic: topic)))")
    }
    for word in words {
      lines.append(
        "complete -c flash -n __fish_use_subcommand -a \(fishQuote(word.name)) "
          + "-d \(fishQuote(word.description))")
    }
    for entry in entries {
      lines.append(
        "complete -c flash -n "
          + fishQuote(
            "__fish_seen_subcommand_from \(entry.topic); and test (count (commandline -opc)) -eq 2")
          + " -a \(fishQuote(entry.action)) -d \(fishQuote(entry.summary))")
      for option in entry.options {
        let name = String(option.name.dropFirst(2))
        var line =
          "complete -c flash -n \(fishQuote("__flash_at_command \(entry.topic) \(entry.action)")) "
          + "-l \(name) -d \(fishQuote(option.syntax))"
        if let values = option.values {
          line += " -x"
          if !values.isEmpty { line += " -a \(fishQuote(values.joined(separator: " ")))" }
        }
        lines.append(line)
      }
    }
    lines.append("")
    return lines.joined(separator: "\n")
  }

  // MARK: man page

  /// roff text: escape the backslash and a leading control character, and
  /// write hyphens as minus signs where they are options.
  private static func roff(_ text: String) -> String {
    var escaped = text.replacingOccurrences(of: "\\", with: "\\e")
      .replacingOccurrences(of: "-", with: "\\-")
    if escaped.hasPrefix(".") || escaped.hasPrefix("'") { escaped = "\\&" + escaped }
    return escaped
  }

  /// A roff text line as lines under 80 bytes; roff joins them back.
  private static func wrapped(_ line: String) -> [String] {
    guard !line.hasPrefix("."), line.utf8.count > 78 else { return [line] }
    var lines: [String] = []
    var current = ""
    for word in line.split(separator: " ") {
      if !current.isEmpty, current.utf8.count + 1 + word.utf8.count > 78 {
        lines.append(current)
        current = ""
      }
      current += (current.isEmpty ? "" : " ") + word
    }
    if !current.isEmpty { lines.append(current) }
    // A line that starts with a control character would be read as a request.
    return lines.map { $0.hasPrefix(".") || $0.hasPrefix("'") ? "\\&" + $0 : $0 }
  }

  static func manPage(date: Date = Date()) -> String {
    let day = ISO8601DateFormatter.string(
      from: date, timeZone: TimeZone(identifier: "UTC")!, formatOptions: [.withFullDate])
    var lines = [
      ".TH FLASH 1 \(day) \"Flash\" \"User Commands\"",
      ".SH NAME",
      "flash \\- keyboard hints, modes and automation for macOS",
      ".SH SYNOPSIS",
      ".B flash",
      "[\\fB\\-\\-json\\fR]",
      ".I topic action",
      "[\\fB\\-\\-name\\fR=\\fIvalue\\fR ...]",
      ".br",
      ".B flash",
      "[\\fB\\-\\-json\\fR]",
      ".I word",
      "\\&...",
      ".SH DESCRIPTION",
      roff(
        "flash runs the words you would type after : in Flash, in the running resident, and "
          + "exits with how the run ended. The same grammar as the command line: a command "
          + "(flash tab next), a vim ex command (flash q, flash tabn), each word by its unique "
          + "prefix (flash ta nex), a plugin command (flash screenshot window), or one of the "
          + "words below. Scripts should spell commands in full: a prefix can become ambiguous "
          + "when a plugin adds a command. The words reach the resident over its local socket; "
          + "when Flash is not running, flash opens it and waits for the socket."),
      ".SH OPTIONS",
      ".TP", ".B \\-\\-json",
      roff(
        "Print the reply as one JSON object (status, output, message) instead of the output "
          + "and the message. The exit status is the same."),
      ".SH COMMANDS",
    ]
    for topic in topics {
      lines.append(".SS \(topic)")
      for entry in entries where entry.topic == topic {
        let options = entry.options.map(\.syntax).joined(separator: " ")
        lines.append(".TP")
        lines.append(
          "\\fBflash \(entry.topic) \(entry.action)\\fR"
            + (options.isEmpty ? "" : " " + roff(options)))
        lines.append(roff(entry.summary))
      }
    }
    lines.append(".SH OTHER WORDS")
    for word in words {
      lines += [".TP", "\\fBflash \(word.name)\\fR", roff(word.description)]
    }
    lines += [
      ".SH EXIT STATUS",
      ".TP", "0", "The command ran.",
      ".TP", "1", "It failed, or found nothing to act on.",
      ".TP", "2", "The words name no command, or more than one.",
      ".SH ENVIRONMENT",
      ".TP", ".B FLASH_CONFIG", roff("The configuration file to read instead of the default."),
      ".TP", ".B XDG_CONFIG_HOME",
      roff("When set, the configuration is $XDG_CONFIG_HOME/flash/flash.toml."),
      ".TP", ".B FLASH_<SECTION>_<KEY>",
      roff("Overrides one configuration key, such as FLASH_DEBUG_LOG_LEVEL=trace."),
      ".SH FILES",
      ".TP", ".I ~/.config/flash/flash.toml",
      roff("The configuration, validated by flash config check."),
      ".TP", ".I ~/Library/Logs/Flash/flash.log", roff("Newline-delimited JSON logs."),
      ".TP", ".I ~/Library/Application Support/Flash/run/flash.sock",
      roff("The resident's socket, which flash speaks; only your account can use it."),
      ".TP", ".I ~/Library/Application Support/Flash/",
      roff("Clipboard history, frecency, marks and plugin data."),
      ".SH SEE ALSO",
      roff(
        "flash help show, the documentation bundled with Flash, whose IPC protocol page "
          + "describes the socket; flash config schema, the configuration's JSON Schema."),
      "",
    ]
    return lines.flatMap(wrapped).joined(separator: "\n")
  }
}

extension FlashQuery {
  /// The `--options` a query takes, for completion and the man page.
  var options: [CLIReference.Option] {
    switch self {
    case .status, .doctor:
      return [CLIReference.Option(name: "--json", values: nil, syntax: "[--json]")]
    case .configCheck:
      return [CLIReference.Option(name: "--file", values: [], syntax: "[--file=<path>]")]
    case .configSchema, .manPage:
      return []
    case .eventsWatch:
      return [
        CLIReference.Option(name: "--name", values: [], syntax: "[--name=<glob,...>]"),
        CLIReference.Option(name: "--count", values: [], syntax: "[--count=<n>]"),
      ]
    case .completion:
      return [
        CLIReference.Option(
          name: "--shell", values: CLIReference.Shell.allCases.map(\.rawValue),
          syntax: "--shell=<zsh|bash|fish>")
      ]
    }
  }
}
