import AppKit
import CryptoKit
import Foundation

/// What one user copy is allowed to become in clipboard history.
///
/// The monitor reads the general pasteboard; this type decides which
/// representation is kept. Password-manager markers still exclude the whole
/// payload. A copied file wins over the small TIFF icon Finder puts beside
/// it. Image bytes stay out of the plugin event: the host writes them under
/// the clipboard plugin's data directory and the event only names the file.
enum ClipboardCapture {
  static let maxTextBytes = 128 * 1024
  static let maxHTMLBytes = 64 * 1024
  static let maxImageBytes = 4 * 1024 * 1024
  static let maxFiles = 20

  struct Item: Equatable {
    enum Kind: String, Equatable {
      case text
      case image
      case html
      case files
    }

    var kind: Kind
    var text: String
    var html: String?
    var image: Data?
    var mime: String?
    var files: [String]
    var sha256: String?
  }

  private static let unrecorded: Set<String> = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
  ]

  private static let imageTypes: [(type: String, mime: String)] = [
    ("public.png", "image/png"),
    ("public.jpeg", "image/jpeg"),
    ("public.gif", "image/gif"),
    ("public.webp", "image/webp"),
    ("org.webmproject.webp", "image/webp"),
  ]

  /// 32 lowercase hex characters, the only id the history routes accept.
  static func makeID() -> String {
    UUID().uuidString.replacingOccurrences(of: "-", with: "").lowercased()
  }

  static func isEntryID(_ id: String) -> Bool {
    id.utf8.count == 32
      && id.utf8.allSatisfy { byte in (48...57).contains(byte) || (97...102).contains(byte) }
  }

  static func sha256Hex(_ data: Data) -> String {
    SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
  }

  /// Choose a history item from representations the caller already read.
  /// `image` is a pasteboard image and is ignored when `filePaths` is
  /// non-empty. `imageFile` is the bytes of a single copied image file.
  static func capture(
    types: [String],
    plain: String?,
    html: String?,
    image: (mime: String, bytes: Data)?,
    filePaths: [String],
    imageFile: (mime: String, bytes: Data)?
  ) -> Item? {
    if types.contains(where: unrecorded.contains) { return nil }
    let files = Array(filePaths.prefix(maxFiles)).filter { !$0.isEmpty }
    if !files.isEmpty {
      let text = cappedUTF8(plain ?? files.joined(separator: "\n"), maxBytes: maxTextBytes)
      if files.count == 1, let stored = storedImage(imageFile) {
        return Item(
          kind: .files, text: text, html: nil, image: stored.bytes, mime: stored.mime,
          files: files, sha256: sha256Hex(stored.bytes))
      }
      return Item(
        kind: .files, text: text, html: nil, image: nil, mime: nil, files: files, sha256: nil)
    }
    if let stored = storedImage(image) {
      return Item(
        kind: .image, text: cappedUTF8(plain ?? "", maxBytes: maxTextBytes), html: nil,
        image: stored.bytes, mime: stored.mime, files: [], sha256: sha256Hex(stored.bytes))
    }
    if let html, !html.isEmpty {
      let body = cappedUTF8(html, maxBytes: maxHTMLBytes)
      guard !body.isEmpty else { return nil }
      return Item(
        kind: .html, text: cappedUTF8(plain ?? "", maxBytes: maxTextBytes), html: body,
        image: nil, mime: nil, files: [], sha256: nil)
    }
    guard let plain, !plain.isEmpty, plain.utf8.count <= maxTextBytes else { return nil }
    return Item(kind: .text, text: plain, html: nil, image: nil, mime: nil, files: [], sha256: nil)
  }

  /// Read the general (or a test) pasteboard into one history item.
  static func read(_ pasteboard: NSPasteboard) -> Item? {
    let types = (pasteboard.types ?? []).map(\.rawValue)
    let paths = filePaths(on: pasteboard)
    let image = paths.isEmpty ? pasteboardImage(pasteboard) : nil
    let html = paths.isEmpty && image == nil ? pasteboardHTML(pasteboard) : nil
    return capture(
      types: types,
      plain: pasteboard.string(forType: .string),
      html: html,
      image: image,
      filePaths: paths,
      imageFile: imageFile(at: paths))
  }

  static func pngData(fromTIFF data: Data) -> Data? {
    guard let rep = NSBitmapImageRep(data: data) else { return nil }
    let png = rep.representation(using: .png, properties: [:])
    guard let png, !png.isEmpty else { return nil }
    return png
  }

  private static func storedImage(_ image: (mime: String, bytes: Data)?) -> (
    mime: String, bytes: Data
  )? {
    guard let image, !image.bytes.isEmpty, image.bytes.count <= maxImageBytes,
      ClipboardImageStore.ext(for: image.mime) != nil
    else { return nil }
    return image
  }

  private static func filePaths(on pasteboard: NSPasteboard) -> [String] {
    let options: [NSPasteboard.ReadingOptionKey: Any] = [.urlReadingFileURLsOnly: true]
    if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: options) as? [URL] {
      let paths = urls.compactMap { url -> String? in
        guard url.isFileURL else { return nil }
        return url.path
      }
      if !paths.isEmpty { return paths }
    }
    let legacy = NSPasteboard.PasteboardType("NSFilenamesPboardType")
    if let names = pasteboard.propertyList(forType: legacy) as? [String] {
      let paths = names.filter { !$0.isEmpty }
      if !paths.isEmpty { return paths }
    }
    return []
  }

  /// Bytes of a single copied image file, when it is a regular file inside
  /// the image cap. Several files stay a path list; the pasteboard's TIFF
  /// icon is not a preview.
  private static func imageFile(at paths: [String]) -> (mime: String, bytes: Data)? {
    guard paths.count == 1 else { return nil }
    let path = paths[0]
    let mime: String
    switch (path as NSString).pathExtension.lowercased() {
    case "png": mime = "image/png"
    case "jpg", "jpeg": mime = "image/jpeg"
    case "gif": mime = "image/gif"
    case "webp": mime = "image/webp"
    default: return nil
    }
    let url = URL(fileURLWithPath: path)
    guard
      let values = try? url.resourceValues(forKeys: [.fileSizeKey, .isRegularFileKey]),
      values.isRegularFile == true,
      let size = values.fileSize,
      size > 0, size <= maxImageBytes,
      let bytes = try? Data(contentsOf: url),
      !bytes.isEmpty, bytes.count <= maxImageBytes
    else { return nil }
    return (mime, bytes)
  }

  private static func pasteboardImage(_ pasteboard: NSPasteboard) -> (mime: String, bytes: Data)? {
    for (type, mime) in imageTypes {
      guard let data = pasteboard.data(forType: NSPasteboard.PasteboardType(type)),
        !data.isEmpty, data.count <= maxImageBytes
      else { continue }
      return (mime, data)
    }
    guard let tiff = pasteboard.data(forType: .tiff),
      let png = pngData(fromTIFF: tiff),
      png.count <= maxImageBytes
    else { return nil }
    return ("image/png", png)
  }

  private static func pasteboardHTML(_ pasteboard: NSPasteboard) -> String? {
    let htmlType = NSPasteboard.PasteboardType("public.html")
    if let html = pasteboard.string(forType: htmlType), !html.isEmpty { return html }
    let rtfType = NSPasteboard.PasteboardType("public.rtf")
    guard let rtf = pasteboard.data(forType: rtfType),
      let text = NSAttributedString(rtf: rtf, documentAttributes: nil)
    else { return nil }
    let range = NSRange(location: 0, length: text.length)
    guard
      let data = try? text.data(
        from: range,
        documentAttributes: [.documentType: NSAttributedString.DocumentType.html]),
      let html = String(data: data, encoding: .utf8),
      !html.isEmpty
    else { return nil }
    return html
  }

  private static func cappedUTF8(_ text: String, maxBytes: Int) -> String {
    let bytes = Array(text.utf8)
    guard bytes.count > maxBytes else { return text }
    guard maxBytes > 0 else { return "" }
    var end = maxBytes
    while end > 0, end < bytes.count, bytes[end] & 0b1100_0000 == 0b1000_0000 {
      end -= 1
    }
    return String(decoding: bytes[..<end], as: UTF8.self)
  }
}

/// Image files for clipboard history. The host writes one file before it
/// emits `core:clipboard.changed`; the plugin deletes it when the entry goes
/// away. Names are `<id>.<ext>` and nothing else.
enum ClipboardImageStore {
  static func ext(for mime: String) -> String? {
    switch mime {
    case "image/png": "png"
    case "image/jpeg": "jpg"
    case "image/gif": "gif"
    case "image/webp": "webp"
    default: nil
    }
  }

  static func fileURL(dataDir: URL, id: String, mime: String) -> URL? {
    guard ClipboardCapture.isEntryID(id), let ext = ext(for: mime) else { return nil }
    return dataDir.appendingPathComponent("share/images/\(id).\(ext)")
  }

  /// Payload for `core:clipboard.changed`. Image bytes are written beside
  /// the plugin's history and are not part of the dictionary. Nil when an
  /// image entry could not be stored, or `id` is not a history id.
  static func changedPayload(for item: ClipboardCapture.Item, dataDir: URL, id: String)
    -> [String: Any]?
  {
    guard ClipboardCapture.isEntryID(id) else { return nil }
    var payload: [String: Any] = [
      "id": id,
      "kind": item.kind.rawValue,
      "text": item.text,
    ]
    if let html = item.html, !html.isEmpty { payload["html"] = html }
    if !item.files.isEmpty { payload["files"] = item.files }
    guard let mime = item.mime, let image = item.image else { return payload }
    guard write(dataDir: dataDir, id: id, mime: mime, bytes: image) else {
      return item.kind == .image ? nil : payload
    }
    payload["mime"] = mime
    payload["sha256"] = item.sha256 ?? ClipboardCapture.sha256Hex(image)
    return payload
  }

  private static func write(dataDir: URL, id: String, mime: String, bytes: Data) -> Bool {
    guard let url = fileURL(dataDir: dataDir, id: id, mime: mime), !bytes.isEmpty,
      bytes.count <= ClipboardCapture.maxImageBytes
    else { return false }
    let images = url.deletingLastPathComponent()
    let share = images.deletingLastPathComponent()
    do {
      try FileManager.default.createDirectory(at: images, withIntermediateDirectories: true)
      try setOwnerOnly(dataDir, isDirectory: true)
      try setOwnerOnly(share, isDirectory: true)
      try setOwnerOnly(images, isDirectory: true)
      try bytes.write(to: url, options: .atomic)
      try setOwnerOnly(url, isDirectory: false)
      return true
    } catch {
      return false
    }
  }

  private static func setOwnerOnly(_ url: URL, isDirectory: Bool) throws {
    try FileManager.default.setAttributes(
      [.posixPermissions: isDirectory ? 0o700 : 0o600], ofItemAtPath: url.path)
  }
}
