// Unicode 17.0 scalar widths from utf8proc 2.11.3, compacted into non-unit
// intervals. Private-use scalars have width one, matching tmux's wrapper.
enum StatusFormatUnicodeData {
  static func width(_ scalar: UInt32) -> Int {
    var lower = 0
    var upper = intervals.count
    while lower < upper {
      let middle = lower + (upper - lower) / 2
      let interval = intervals[middle]
      if scalar < interval.0 {
        upper = middle
      } else if scalar > interval.1 {
        lower = middle + 1
      } else {
        return interval.2
      }
    }
    return 1
  }

